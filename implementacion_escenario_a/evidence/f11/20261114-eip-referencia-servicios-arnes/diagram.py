old_resource,old_pattern,old_arrow,old_text=resource,pattern,arrow,text
def resource(x,y,w,title,body='',h=140):
    y+=100
    d.rounded_rectangle((x-w/2,y,x+w/2,y+h),radius=12,fill='#F2F5F7',outline='#A8B6C2',width=3)
    old_text(x,y+18,title,38,True,width=w-20)
    if body: old_text(x,y+66,body,35,width=w-20)
def pattern(name,x,y,label,body,width=340):
    y+=100
    old_text(x,y,label,38,True,width=width)
    height=icon(name,x,y+55)
    old_text(x,y+height+95,body,36,width=width)
def arrow(points,*a,**kw): return old_arrow([(x,y+100) for x,y in points],*a,**kw)
def text(x,y,*a,**kw): return old_text(x,y+100,*a,**kw)
